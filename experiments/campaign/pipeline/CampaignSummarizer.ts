/**
 * CampaignSummarizer — 战役汇总器
 *
 * 汇总所有实验的 metrics + tests，生成总体摘要。
 */

import * as fs from "fs";
import * as path from "path";
import type { ExperimentMetrics, TestResult, CampaignSummary } from "../types";

export function summarizeCampaign(
  allMetrics: ExperimentMetrics[],
  allTests: TestResult[],
  totalRuns: number,
  outputDir: string,
): CampaignSummary {
  const testByExp = new Map<string, TestResult[]>();
  for (const t of allTests) {
    if (!testByExp.has(t.experimentId)) testByExp.set(t.experimentId, []);
    testByExp.get(t.experimentId)!.push(t);
  }

  const experiments: CampaignSummary["experiments"] = [];
  const conclusions: string[] = [];

  for (const metrics of allMetrics) {
    const tests = testByExp.get(metrics.experimentId) || [];
    const mainTest = tests[0];
    const allSignificant = tests.every(t => t.significant);

    experiments.push({
      id: metrics.experimentId,
      hypothesis: `H${metrics.experimentId.split("_")[0].slice(1)}`,
      status: allSignificant ? "completed" : "partial",
      runsCompleted: metrics.sampleSize,
      runsPlanned: metrics.sampleSize,
      keyResult: mainTest?.conclusion || "No test results",
      significant: allSignificant,
      pValue: mainTest?.pValue || 1,
      effectSize: mainTest?.effectSize || 0,
    });

    if (mainTest?.significant) {
      conclusions.push(`✅ ${mainTest.conclusion}`);
    } else {
      conclusions.push(`❌ ${mainTest?.conclusion || "No significant result"}`);
    }
  }

  const summary: CampaignSummary = {
    timestamp: new Date().toISOString(),
    totalExperiments: allMetrics.length,
    totalRuns,
    experiments,
    overallConclusions: conclusions,
  };

  // 保存
  const summaryPath = path.join(outputDir, "campaign_summary.json");
  fs.writeFileSync(summaryPath, JSON.stringify(summary, null, 2));

  // 生成 Markdown 摘要
  const mdLines: string[] = [];
  mdLines.push("# SwarmAlpha Experimental Campaign — Summary");
  mdLines.push("");
  mdLines.push(`**Generated:** ${summary.timestamp}`);
  mdLines.push(`**Total Experiments:** ${summary.totalExperiments}`);
  mdLines.push(`**Total Runs:** ${summary.totalRuns}`);
  mdLines.push("");
  mdLines.push("## Results");
  mdLines.push("");
  mdLines.push("| Experiment | Hypothesis | Significant | p-value | Effect Size | Key Result |");
  mdLines.push("|------------|------------|-------------|---------|-------------|------------|");
  for (const exp of experiments) {
    const sig = exp.significant ? "✅" : "❌";
    mdLines.push(`| ${exp.id} | ${exp.hypothesis} | ${sig} | ${exp.pValue.toFixed(4)} | ${exp.effectSize.toFixed(3)} | ${exp.keyResult.slice(0, 80)}... |`);
  }
  mdLines.push("");
  mdLines.push("## Conclusions");
  mdLines.push("");
  for (const c of conclusions) {
    mdLines.push(`- ${c}`);
  }
  mdLines.push("");
  mdLines.push("---");
  mdLines.push("");
  mdLines.push("*Auto-generated by SwarmAlpha Campaign Pipeline.*");

  const mdPath = path.join(outputDir, "campaign_summary.md");
  fs.writeFileSync(mdPath, mdLines.join("\n"));

  return summary;
}