/**
 * 危机响应优先级排序任务 (Crisis Response Prioritization)
 *
 * 设计目标：
 * 1. 真正的隐藏档案——正确答案需要跨维度权衡，不是简单拼凑
 * 2. 认知偏差可触发——即使信息充分共享，agent 仍可能因锚定/从众而选错
 * 3. 不泄露答案——agent 只掌握原始数据点，不含推理结论
 * 4. 现实场景——危机响应是多 agent 协作的典型场景
 *
 * 任务：5 个专家评估 5 个危机响应方案，按优先级排序。
 * 每个专家掌握一个维度的原始数据。
 *
 * ─── 为什么旧任务失败 ───
 * 旧 Invest 任务中，每个 agent 的 knownItems 自带推理结论
 * （如"增速在下降""TAM 在缩水"），信息共享后答案自然浮现。
 *
 * 新任务中，agent 只掌握原始数值，不带判断。
 * 正确答案需要权衡 5 个维度，且维度间存在张力：
 * - 速度快的方案成本高
 * - 覆盖广的方案精度低
 * - 效果好的方案风险大
 *
 * ─── 隐藏档案设计 ───
 * 5 个方案 × 5 个维度 = 25 个数据点
 * 每个 agent 掌握全部 5 个方案在自己维度的数据（不是只知道部分方案）
 * 隐藏点在于：没有任何单个维度能独立决定排序
 *
 * ─── 认知偏差触发机制 ───
 * 1. 锚定：sharedBriefing 中暗示"速度最重要"，但实际不是
 * 2. 从众：第一个发言的 agent 角色是"速度评估师"，会先给出速度维度排序
 * 3. 确认偏误：每个 agent 的 initialBias 倾向于自己的维度最重要
 * 4. 权威偏置：方案 A 在 3 个维度上排名第一，容易被当作"综合最优"，
 *    但实际排名只有第 3，因为它在 2 个关键维度上很差
 *
 * ─── Ground Truth ───
 * 正确排序需要加权综合：效果(0.30) + 风险控制(0.25) + 可持续性(0.20) + 覆盖度(0.15) + 速度(0.10)
 *
 * 排名：C > B > A > E > D
 *
 * 关键张力：
 * - 方案 A 在速度/覆盖/可持续性 3 个维度第一 → 看似最优
 * - 但效果第 4、风险第 5 → 权重最高的两个维度最差
 * - 方案 C 在效果和风险两个高权重维度第一 → 综合最优
 * - 方案 B 均衡在第 2 → 综合第 2
 */

